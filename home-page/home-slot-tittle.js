        function drawGlyphAt(colOffset, glyph, color, glow) {
            var rows = glyph.length;
            var cols = glyph[0].length;
            var cellW = (LETTER_W * CELL) / cols;
            var cellH = (LETTER_H * CELL) / rows;
            var gap = Math.max(0.5, Math.min(cellW, cellH) * 0.08);
            var baseX = colOffset * CELL;
            if (glow) {
                ctx.shadowColor = color;
                ctx.shadowBlur = CELL * 0.6;
            } else {
                ctx.shadowBlur = 0;
            }
            ctx.fillStyle = color;
            for (var r = 0; r < rows; r++) {
                for (var c = 0; c < cols; c++) {
                    if (glyph[r][c]) {
                        ctx.fillRect(baseX + c * cellW, r * cellH, cellW - gap, cellH - gap);
                    }
                }
            }
            ctx.shadowBlur = 0;
        }

